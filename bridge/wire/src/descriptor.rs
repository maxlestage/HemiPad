#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_descriptor_declares_both_reports() {
        // 0x85 0x01 : Report ID (1), la manette. 0x85 0x02 : le clavier.
        assert!(HID_REPORT_DESCRIPTOR
            .windows(2)
            .any(|pair| pair == [0x85, 0x01]));
        assert!(HID_REPORT_DESCRIPTOR
            .windows(2)
            .any(|pair| pair == [0x85, 0x02]));
    }

    #[test]
    fn the_descriptor_opens_and_closes_its_collections() {
        // Deux collections applicatives (0xA1 0x01), une physique (0xA1 0x00),
        // et autant de fins de collection (0xC0).
        let opened = HID_REPORT_DESCRIPTOR
            .windows(2)
            .filter(|pair| pair[0] == 0xA1)
            .count();
        let closed = HID_REPORT_DESCRIPTOR.iter().filter(|&&b| b == 0xC0).count();
        assert_eq!(opened, 3);
        assert_eq!(closed, 3);
    }

    #[test]
    fn the_descriptor_starts_with_a_gamepad() {
        // Usage Page (Generic Desktop), Usage (Game Pad).
        assert_eq!(&HID_REPORT_DESCRIPTOR[..4], &[0x05, 0x01, 0x09, 0x05]);
    }
}
